class Account():
  def __init__(self,acc_name,acc_num):
    self.acc_name=acc_name
    self.acc_num=acc_num
    self.__acc_balance=30000
    self.transactions=[]
#Method to get private balance safely
  def get_acc_balance(self):
      return self.__acc_balance
#deposit method by using function and conditional statement
  def deposit(self,amount):
    try:
       if amount>0:
         self.__acc_balance=self.__acc_balance+amount
         self.transactions.append(f"Deposit: {amount}")
       else:
        raise ValueError
    except ValueError:
      print("Enter Valid Amount")
#withdrawal method by using function and conditional statement
  def withdrawal(self,amount):
    try:
      if amount<=0:
        raise TypeError
      if amount<=self.__acc_balance:
           self.__acc_balance=self.__acc_balance-amount
           self.transactions.append(f"Withdrawal: {amount}")
      else:
        raise ValueError
    except TypeError:
      print("Enter Valid Amount")
    except ValueError:
      print("Insufficient Balance")
  #Transfer method by using function and conditional statement
  def transfer(self,to_account,amount):
    if amount<=0:
      print("Enter Valid Amount")
      return
    if self.__acc_balance<amount:
      print("Insufficient Balance")
      return
    self.__acc_balance-=amount
    to_account.__acc_balance+=amount
    self.transactions.append(f"Transfer: {amount}")
    to_account.transactions.append(f"Transfer: {amount}")
    print(f"Transfered amount {amount}-Rs from Acc_num {self.acc_num} to Acc_num {to_account.acc_num} ")
#Transaction history-exception handling
  def transaction(self):
    try:
      for i in self.transactions:
        print(i)
    except Exception as e:
      print(e)
